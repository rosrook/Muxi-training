#!/usr/bin/env bash
# Create a new self-contained training run package (scripts/config copied, not shared).
#
#   bash tools/create_run.sh --run-id ID --sft /path/sft_dataset.jsonl [--config path.yaml]
#
set -euo pipefail
TRAIN_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TEMPLATE="${TRAIN_ROOT}/templates/lora_4gpu"
DATA_ROOT="${DATA_ROOT:-/mnt/public/data/zhuxz/training_runs}"

RUN_ID=""
SFT=""
CONFIG=""
DESCRIPTION=""
NPROC=4
CUDA_DEVICES="0,1,2,3"
MASTER_PORT="29531"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --run-id) RUN_ID="$2"; shift 2 ;;
    --sft) SFT="$2"; shift 2 ;;
    --config) CONFIG="$2"; shift 2 ;;
    --description) DESCRIPTION="$2"; shift 2 ;;
    --nproc) NPROC="$2"; shift 2 ;;
    --cuda-devices) CUDA_DEVICES="$2"; shift 2 ;;
    --master-port) MASTER_PORT="$2"; shift 2 ;;
    -h|--help)
      sed -n '1,12p' "$0"; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

if [[ -z "${RUN_ID}" || -z "${SFT}" ]]; then
  echo "usage: $0 --run-id ID --sft /path/sft_dataset.jsonl [--config yaml]" >&2
  exit 2
fi
if [[ ! -f "${SFT}" ]]; then
  echo "SFT not found: ${SFT}" >&2
  exit 1
fi

CODE_RUN="${TRAIN_ROOT}/runs/${RUN_ID}"
DATA_RUN="${DATA_ROOT}/${RUN_ID}"
if [[ -e "${CODE_RUN}" ]]; then
  echo "already exists: ${CODE_RUN}" >&2
  exit 1
fi

mkdir -p "${CODE_RUN}/scripts" "${DATA_RUN}/checkpoints" "${DATA_RUN}/tensorboard" "${DATA_RUN}/outputs"
cp -a "${TEMPLATE}/scripts/train_worker.py" "${CODE_RUN}/scripts/"
cp -a "${TEMPLATE}/scripts/train_launch.sh" "${CODE_RUN}/scripts/"
cp -a "${TEMPLATE}/run.sh" "${CODE_RUN}/run.sh"
chmod +x "${CODE_RUN}/run.sh" "${CODE_RUN}/scripts/train_launch.sh" "${CODE_RUN}/scripts/train_worker.py"

if [[ -n "${CONFIG}" && -f "${CONFIG}" ]]; then
  cp -a "${CONFIG}" "${CODE_RUN}/config.yaml"
else
  cp -a "${TEMPLATE}/config.yaml" "${CODE_RUN}/config.yaml"
fi

# Pin SFT as symlink inside data run (absolute).
ln -sfn "$(readlink -f "${SFT}")" "${DATA_RUN}/sft_dataset.jsonl"

cat > "${CODE_RUN}/run_env.sh" <<EOF
# Generated by create_run.sh — owned by this run only.
export RUN_ID="${RUN_ID}"
export SFT_DATASET="${DATA_RUN}/sft_dataset.jsonl"
export TRAINING_CONFIG="${CODE_RUN}/config.yaml"
export CHECKPOINT_DIR="${DATA_RUN}/checkpoints"
export TENSORBOARD_DIR="${DATA_RUN}/tensorboard"
export OUTPUT_DIR="${DATA_RUN}/outputs"
export MODEL_SOURCE="\${MODEL_SOURCE:-/mnt/public/model/Qwen3.5-4B}"
export MODEL_LINK="\${MODEL_LINK:-/mnt/public/data/zhuxz/models/Qwen3.5-4B}"
export BPG_SRC="\${BPG_SRC:-/mnt/public/code/zhuxz/bench_probe_gen/src}"
export TRAINING_BACKEND="\${TRAINING_BACKEND:-native}"
export NPROC_PER_NODE="\${NPROC_PER_NODE:-${NPROC}}"
export CUDA_DEVICES="\${CUDA_DEVICES:-${CUDA_DEVICES}}"
export MASTER_ADDR="\${MASTER_ADDR:-127.0.0.1}"
export MASTER_PORT="\${MASTER_PORT:-${MASTER_PORT}}"
EOF

cat > "${CODE_RUN}/run_meta.json" <<EOF
{
  "run_id": "${RUN_ID}",
  "status": "ready_to_train",
  "description": $(python3 -c 'import json,sys; print(json.dumps(sys.argv[1]))' "${DESCRIPTION}"),
  "code_dir": "${CODE_RUN}",
  "data_dir": "${DATA_RUN}",
  "sft_dataset": "$(readlink -f "${SFT}")",
  "config": "${CODE_RUN}/config.yaml",
  "created_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}
EOF

cat > "${DATA_RUN}/manifest.json" <<EOF
{
  "run_id": "${RUN_ID}",
  "kind": "new_run",
  "code_dir": "${CODE_RUN}",
  "sft_dataset_resolved": "$(readlink -f "${SFT}")",
  "checkpoints": "${DATA_RUN}/checkpoints",
  "tensorboard": "${DATA_RUN}/tensorboard",
  "outputs": "${DATA_RUN}/outputs"
}
EOF

cat > "${CODE_RUN}/README.md" <<EOF
# Training run \`${RUN_ID}\`

Self-contained package (scripts/config are local copies).

## Paths

- code: \`${CODE_RUN}\`
- data: \`${DATA_RUN}\`
- sft: \`${DATA_RUN}/sft_dataset.jsonl\` → $(readlink -f "${SFT}")

## Train

\`\`\`bash
bash ${CODE_RUN}/run.sh
\`\`\`

Override GPUs: \`CUDA_DEVICES=0,1,2,3 NPROC_PER_NODE=4 bash run.sh\`
EOF

cp -a "${CODE_RUN}/README.md" "${DATA_RUN}/README.md"

echo "[create_run] code -> ${CODE_RUN}"
echo "[create_run] data -> ${DATA_RUN}"
echo "[create_run] launch: bash ${CODE_RUN}/run.sh"
